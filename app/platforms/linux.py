    def current_option(self, browser: Browser) -> GpuOption:
        try:
            options = self.list_options()
            path = self._override_path(browser.id)
            if self._path_exists(path):
                entry = _parse_desktop_entry(path) or {}
                mode = _strip_text(entry.get(MARKER_MODE, ""))
                if mode:
                    for option in options:
                        if option.id == mode:
                            return option
                    synthesized = self._synthesize_option(mode)
                    if synthesized is not None:
                        return synthesized
            return options[0]
        except Exception as exc:
            self._record("current_option", exc)
            return _default_option()

    # -- process detection -------------------------------------------------
    def _iter_proc_pids(self) -> List[int]:
        try:
            names = os.listdir(str(self.proc_root))
        except (OSError, ValueError):
            return []
        pids: List[int] = []
        for name in names:
            if not str(name).isdigit():
                continue
            try:
                pids.append(int(name))
            except (TypeError, ValueError):
                continue
        return pids

    def _process_names(self, browser: Browser) -> frozenset:
        names: Set[str] = set()
        try:
            for name in getattr(browser, "process_names", ()) or ():
                base = _basename(name).lower()
                if base:
                    names.add(base)
            executable = _basename(getattr(browser, "executable", "")).lower()
            if executable:
                names.add(executable)
            command = list(getattr(browser, "command", ()) or ())
            if command:
                index = _command_index(command)
                base = _basename(command[index]).lower()
                if base:
                    names.add(base)
            package = _strip_text(getattr(browser, "package", "")).lower()
            if package:
                names.add(package)
                last = package.rsplit(".", 1)[-1]
                names.add(last)
                match = _match_known_browser(last)
                if match is not None:
                    names.update(match[2])
            match = _match_known_browser(executable)
            if match is not None:
                names.update(match[2])
        except Exception as exc:
            self._record("process names", exc)
        return frozenset(
            name for name in names if name and name not in GENERIC_PROCESS_NAMES
        )

    def _flatpak_ids(self, browser: Browser) -> frozenset:
        package = _strip_text(getattr(browser, "package", "")).lower()
        return frozenset({package}) if package else frozenset()

    def _pid_matches(
        self, pid: int, names: frozenset, app_ids: frozenset
    ) -> bool:
        base = self.proc_root / str(pid)
        exe_target = _read_link(base / "exe").replace(" (deleted)", "").strip()
        if exe_target:
            if _basename(exe_target).lower() in names:
                return True
            if exe_target.lower() in app_ids:
                return True
        try:
            raw_cmdline = (base / "cmdline").read_bytes()
        except (OSError, ValueError):
            raw_cmdline = b""
        if raw_cmdline:
            text = raw_cmdline.decode("utf-8", "replace")
            for token in text.split("\x00"):
                token = token.strip()
                if not token:
                    continue
                if token.lower() in app_ids:
                    return True
                if _basename(token).lower() in names:
                    return True
        comm = read_text(base / "comm").strip().lower()
        if comm and comm in names:
            return True
        return False

    def running_pids(self, browser: Browser) -> List[int]:
        try:
            names = self._process_names(browser)
            app_ids = self._flatpak_ids(browser)
            if not names and not app_ids:
                return []
            result: List[int] = []
            for pid in self._iter_proc_pids():
                try:
                    if self._pid_matches(pid, names, app_ids):
                        result.append(pid)
                except (OSError, ValueError):
                    continue
                except Exception as exc:
                    self._record("pid " + str(pid), exc)
                    continue
            return sorted(result)
        except Exception as exc:
            self._record("running_pids", exc)
            return []

    def is_browser_running(self, browser: Browser) -> bool:
        try:
            return bool(self.running_pids(browser))
        except Exception as exc:
            self._record("is_browser_running", exc)
            return False

