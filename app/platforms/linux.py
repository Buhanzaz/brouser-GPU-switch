    def option_env(self, option: Optional[GpuOption]) -> Dict[str, str]:
        """Return the environment variables needed to launch with option."""
        try:
            payload = getattr(option, "payload", None) or {}
            if not isinstance(payload, Mapping):
                return {}
            env: Dict[str, str] = {}
            for key, value in payload.items():
                if isinstance(key, str) and isinstance(value, (str, int, float)):
                    env[key] = str(value)
            return env
        except Exception:
            return {}

    def describe_launch(self, option: Optional[GpuOption]) -> str:
        """Short Russian description of how the browser will be launched."""
        try:
            env = self.option_env(option)
            if not env:
                return "Браузер запускается как обычно: видеокарту выбирает система."
            pairs = ", ".join(key + "=" + value for key, value in sorted(env.items()))
            return "Браузер запускается с переменными окружения: " + pairs + "."
        except Exception:
            return "Браузер запускается как обычно."

