"""Linux platform backend for Browser GPU Switch.

All detection is done with plain file reads - /etc/os-release, sysfs and
/proc - so the backend never needs root rights and never runs external
commands for detection.

Switching is per-user and file based.  For a browser the backend writes

* a small launcher script into the application data directory
  (<data_dir>/wrappers/<id>-<mode>.sh) that exports the GPU related
  environment variables and execs the original browser command, and
* an XDG desktop-entry override in ~/.local/share/applications that points
  Exec at the launcher and carries X-BrowserGpuSwitch-Mode /
  X-BrowserGpuSwitch-Original-Exec markers.

Nothing outside the user's home directory is modified.  Undo only removes
files that carry our markers and were recorded as created_by_us, so a
foreign shortcut is never clobbered.

Every path can be redirected through the constructor (home, data_dir,
state, sysfs_root, proc_root, desktop_dirs, applications_dir, which,
os_release_path, environ) which makes the whole module testable on a
machine without Linux: the unit tests inject fake sysfs and /proc trees
created inside a temporary directory.

Public helpers used by the UI hint and by the tests:

    backend.option_env(option)      -> environment variables for a mode
    backend.describe_launch(option) -> short Russian explanation
"""

