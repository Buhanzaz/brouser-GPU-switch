    def _write_atomic(self, path: Path, text: str, mode: Optional[int] = None) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        temp = path.with_name(path.name + ".gpuswitch.tmp")
        try:
            with temp.open("w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
                handle.flush()
                os.fsync(handle.fileno())
            if mode is not None:
                try:
                    os.chmod(str(temp), mode)
                except OSError:
                    pass
            os.replace(str(temp), str(path))
        finally:
            try:
                if temp.exists():
                    temp.unlink()
            except OSError:
                pass

    def _remove_path(self, path: Path, errors: List[str]) -> bool:
        try:
            if os.path.isdir(str(path)) and not os.path.islink(str(path)):
                errors.append("Это папка, а не файл: " + str(path))
                return False
            os.unlink(str(path))
            return True
        except FileNotFoundError:
            return True
        except OSError as exc:
            errors.append("Не удалось удалить «" + str(path) + "»: " + str(exc))
            return False

