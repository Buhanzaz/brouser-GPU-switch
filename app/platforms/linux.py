def _clean_text(value: Any) -> str:
    """Collapse whitespace/newlines into one line (desktop values, messages)."""
    text = str(value if value is not None else "")
    text = text.replace("\r", " ").replace("\n", " ")
    return re.sub(r"\s+", " ", text).strip()


def _strip_text(value: Any) -> str:
    return str(value if value is not None else "").strip()


def _is_true(value: Any) -> bool:
    return _strip_text(value).lower() in ("true", "1", "yes")


def _basename(token: Any) -> str:
    text = str(token if token is not None else "").strip().replace("\\", "/")
    if not text:
        return ""
    return text.rstrip("/").rsplit("/", 1)[-1]


def _safe_filename(value: Any, fallback: str = "browser") -> str:
    cleaned = SAFE_NAME_RE.sub("_", str(value if value is not None else "")).strip("._-")
    return cleaned or fallback


def _path_key(path: Any) -> str:
    try:
        return os.path.normcase(os.path.abspath(str(path)))
    except (OSError, ValueError):
        return str(path)


def _paths_equal(first: Any, second: Any) -> bool:
    return _path_key(first) == _path_key(second)


def _is_under(path: Any, base: Any) -> bool:
    try:
        resolved = Path(str(path)).resolve()
        root = Path(str(base)).resolve()
        resolved.relative_to(root)
        return True
    except (ValueError, OSError, RuntimeError):
        return False


def _read_link(path: Path) -> str:
    """Return the target of a symlink.

    Real sysfs/proc entries are symlinks; a plain text file with the target
    as its content is accepted too.  The fallback keeps the backend testable
    on operating systems where creating symlinks requires extra privileges.
    """
    try:
        target = os.readlink(str(path))
        if target:
            return str(target)
    except (OSError, ValueError, NotImplementedError):
        pass
    try:
        text = path.read_text(encoding="utf-8", errors="replace").strip()
    except (OSError, ValueError):
        return ""
    return text


def _parse_os_release(text: str) -> Dict[str, str]:
    data: Dict[str, str] = {}
    for raw in str(text).splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        value = value.replace('\\"', '"').replace("\\\\", "\\")
        if key:
            data[key] = value
    return data


def _desktop_unescape(value: Any) -> str:
    text = str(value if value is not None else "")
    escapes = {"s": " ", "n": "\n", "t": "\t", "r": "\r", "\\": "\\"}
    out: List[str] = []
    index = 0
    while index < len(text):
        char = text[index]
        if char == "\\" and index + 1 < len(text):
            follow = text[index + 1]
            if follow in escapes:
                out.append(escapes[follow])
                index += 2
                continue
        out.append(char)
        index += 1
    return "".join(out)


def _desktop_quote(argument: Any) -> str:
    """Quote a single argument for the Exec= key of a desktop entry."""
    text = str(argument if argument is not None else "")
    escaped = text.replace("%", "%%")
    if escaped and re.fullmatch(r"[A-Za-z0-9_./:+@%,\-=]+", escaped):
        return escaped
    escaped = escaped.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    escaped = escaped.replace("+", "+")
    return '"' + escaped + '"'


def _parse_exec(value: Any) -> List[str]:
    """Split an Exec= line into argv, dropping field codes (%U, %f, @@)."""
    text = str(value if value is not None else "").strip()
    if not text:
        return []
    try:
        tokens = shlex.split(text, posix=True)
    except ValueError:
        tokens = text.split()
    result: List[str] = []
    for token in tokens:
        if not isinstance(token, str):
            continue
        if re.fullmatch(r"@@[a-z]?", token):
            continue
        if re.fullmatch(r"%[a-zA-Z]", token):
            continue
        cleaned = token.replace("%%", "\x00")
        cleaned = FIELD_CODE_RE.sub("", cleaned).replace("\x00", "%")
        if cleaned:
            result.append(cleaned)
    return result


def _field_codes(exec_value: Any) -> List[str]:
    codes: List[str] = []
    for match in re.finditer(r"%%|%[a-zA-Z]", str(exec_value if exec_value is not None else "")):
        token = match.group(0)
        if token == "%%":
            continue
        if token not in codes:
            codes.append(token)
    return codes


def _parse_vram_mb(path: Path) -> int:
    raw = _strip_text(read_text(path))
    if not raw:
        return 0
    try:
        size = int(raw)
    except (TypeError, ValueError):
        return 0
    megabytes = size // (1024 * 1024)
    if megabytes <= 0 or megabytes > 1024 * 1024:
        return 0
    return int(megabytes)


def _is_display_class(value: Any) -> bool:
    raw = _strip_text(value).lower()
    if not raw:
        return False
    try:
        number = int(raw, 16)
    except (TypeError, ValueError):
        return False
    return ((number >> 16) & 0xFF) == 0x03


def _match_known_browser(name: Any) -> Optional[Tuple[str, str, Tuple[str, ...]]]:
    base = _basename(name).lower()
    if not base:
        return None
    for prefixes, engine, display, processes in KNOWN_BROWSERS:
        if any(base == prefix or base.startswith(prefix) for prefix in prefixes):
            return (engine, display, tuple(processes))
    return None


def _parse_desktop_entry(path: Path) -> Optional[Dict[str, str]]:
    """Parse the [Desktop Entry] group of a .desktop file; None on failure."""
    text = read_text(path)
    if not text.strip():
        return None
    text = text.lstrip("\ufeff")
    entry: Dict[str, str] = {}
    section = ""
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1].strip()
            continue
        if section != "Desktop Entry" or "=" not in line:
            continue
        key, _, value = line.partition("=")
        entry[key.strip()] = value.strip()
    return entry or None


def _command_index(argv: Sequence[str]) -> int:
    """Index of the real command token, skipping an optional env prefix."""
    if not argv:
        return 0
    index = 0
    if _basename(argv[0]).lower() in ("env", "exec"):
        index = 1
        while index < len(argv) and ENV_ASSIGNMENT_RE.match(argv[index]):
            index += 1
    if index >= len(argv):
        return 0
    return index


def _merge_gpu(existing: Gpu, extra: Gpu) -> Gpu:
    return replace(
        existing,
        driver=existing.driver or extra.driver,
        memory_mb=existing.memory_mb or extra.memory_mb,
        pci_address=existing.pci_address or extra.pci_address,
        detail=existing.detail or extra.detail,
    )


