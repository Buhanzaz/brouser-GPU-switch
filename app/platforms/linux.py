    def diagnostics(self) -> str:
        lines: List[str] = [
            "Backend: LinuxBackend",
            "Platform key: " + LINUX,
        ]
        try:
            info = self.os_info()
            lines.append("OS: " + info.pretty)
            lines.append("Arch: " + (info.arch or "unknown"))
            lines.append("Hostname: " + (info.hostname or "unknown"))
            lines.append("Session: " + (info.session or "unknown"))
        except Exception as exc:
            self._record("diagnostics os_info", exc)
        lines.append("Home: " + str(self.home))
        lines.append("Data dir: " + str(self.data_dir))
        lines.append("Wrappers: " + str(self.wrappers_dir))
        lines.append("Applications dir: " + str(self.applications_dir))
        lines.append(
            "sysfs root: "
            + str(self.sysfs_root)
            + (" (found)" if os.path.isdir(str(self.sysfs_root)) else " (missing)")
        )
        lines.append(
            "proc root: "
            + str(self.proc_root)
            + (" (found)" if os.path.isdir(str(self.proc_root)) else " (missing)")
        )
        try:
            gpus = self.list_gpus()
            lines.append("GPUs: " + str(len(gpus)))
            for gpu in gpus:
                lines.append(
                    "  - "
                    + gpu.id
                    + " | "
                    + gpu.name
                    + " | vendor="
                    + gpu.vendor
                    + " | kind="
                    + gpu.kind
                    + " | driver="
                    + (gpu.driver or "-")
                    + " | memory_mb="
                    + str(gpu.memory_mb)
                )
        except Exception as exc:
            self._record("diagnostics gpus", exc)
        try:
            browsers = self.list_browsers()
            lines.append("Browsers: " + str(len(browsers)))
            for browser in browsers:
                lines.append(
                    "  - "
                    + browser.id
                    + " | "
                    + browser.name
                    + " | "
                    + browser.executable
                    + " | "
                    + browser.source
                )
        except Exception as exc:
            self._record("diagnostics browsers", exc)
        try:
            options = self.list_options()
            lines.append("Options: " + ", ".join(option.id for option in options))
        except Exception as exc:
            self._record("diagnostics options", exc)
        try:
            changes = self.pending_changes()
            lines.append("Applied changes: " + str(len(changes)))
            for change in changes:
                lines.append(
                    "  - "
                    + change.key
                    + " | "
                    + change.option_id
                    + " | "
                    + change.applied_at
                )
        except Exception as exc:
            self._record("diagnostics changes", exc)
        if self._errors:
            lines.append("Errors:")
            lines.extend("  - " + message for message in self._errors[-20:])
        else:
            lines.append("Errors: none")
        return "\n".join(lines)

    def close(self) -> None:
        """Release resources (the backend only uses plain files)."""
        return None


