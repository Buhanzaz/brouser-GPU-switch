    def _find_original_desktop(self, browser: Browser) -> Tuple[Optional[Path], str, Dict[str, str]]:
        candidates: List[Path] = []
        desktop_file = _strip_text(getattr(browser, "desktop_file", ""))
        if desktop_file:
            candidates.append(Path(desktop_file))
        filename = self._override_filename(browser.id)
        for directory in self.desktop_dirs:
            candidates.append(Path(directory) / filename)
        override_path = self._override_path(browser.id)
        seen: Set[str] = set()
        for candidate in candidates:
            key = _path_key(candidate)
            if key in seen:
                continue
            seen.add(key)
            try:
                if not candidate.is_file():
                    continue
            except OSError:
                continue
            if _paths_equal(candidate, override_path):
                continue
            entry = _parse_desktop_entry(candidate)
            if not entry:
                continue
            return (candidate, read_text(candidate), entry)
        return (None, "", {})

    def _read_backup_desktop(self, key: str) -> str:
        try:
            candidates = [self.state.backup_file(key, "original.desktop")]
        except Exception:
            return ""
        for candidate in candidates:
            text = read_text(candidate)
            if text.strip():
                return text
        return ""

    def _wrapper_script(
        self, option: GpuOption, env: Mapping[str, str], original_argv: Sequence[str]
    ) -> str:
        lines = [
            "#!/bin/sh",
            WRAPPER_MARKER + ". Do not edit; use the Restore button to remove it.",
            "# Mode: " + _clean_text(option.id) + " (" + _clean_text(option.label) + ")",
        ]
        for key in sorted(env):
            lines.append("export " + str(key) + "=" + shlex.quote(str(env[key])))
        argv = [str(part) for part in original_argv if str(part)]
        if argv:
            lines.append("exec " + shlex.join(argv) + ' "$@"')
        else:
            lines.append('echo "GPU Switch: the browser launch command is unknown." >&2')
            lines.append("exit 1")
        return "\n".join(lines) + "\n"

    def _build_override(
        self,
        base_text: str,
        browser: Browser,
        option: GpuOption,
        wrapper_path: Path,
        original_exec: str,
        original_desktop_path: str,
    ) -> str:
        codes = _field_codes(original_exec)
        exec_line = " ".join([_desktop_quote(str(wrapper_path))] + codes)
        marker_lines = [
            MARKER_APP + "=" + APP_MARKER_VALUE,
            MARKER_MODE + "=" + _clean_text(option.id),
            MARKER_DESKTOP_ID + "=" + _clean_text(browser.id),
            MARKER_ORIGINAL_EXEC + "=" + _clean_text(original_exec),
            MARKER_ORIGINAL_DESKTOP + "=" + _clean_text(original_desktop_path),
        ]
        if not base_text.strip():
            lines = [
                "[Desktop Entry]",
                "Type=Application",
                "Name=" + _clean_text(browser.name),
                "Exec=" + exec_line,
                "Terminal=false",
                "Categories=Network;WebBrowser;",
            ]
            lines.extend(marker_lines)
            return "\n".join(lines) + "\n"

        output: List[str] = []
        in_entry = False
        wrote_markers = False
        for raw in base_text.splitlines():
            stripped = raw.strip()
            if stripped.startswith("[") and stripped.endswith("]"):
                if in_entry and not wrote_markers:
                    output.extend(marker_lines)
                    wrote_markers = True
                in_entry = stripped == "[Desktop Entry]"
                output.append(raw)
                continue
            if in_entry and "=" in stripped:
                key = stripped.split("=", 1)[0].strip()
                if key == "Exec":
                    output.append("Exec=" + exec_line)
                    continue
                if key in MARKER_KEYS:
                    continue
            output.append(raw)
        if in_entry and not wrote_markers:
            output.extend(marker_lines)
            wrote_markers = True
        text = "\n".join(output)
        if not text.endswith("\n"):
            text += "\n"
        return text

    def _apply(self, browser: Browser, option: Optional[GpuOption]) -> ApplyResult:
        if browser is None or not _strip_text(getattr(browser, "id", "")):
            return ApplyResult.failure(
                "Не удалось определить браузер. Обновите список браузеров и попробуйте снова."
            )
        available = {item.id: item for item in self.list_options()}
        option_id = _strip_text(getattr(option, "id", ""))
        if not option_id:
            return ApplyResult.failure("Не выбран вариант настройки графики.")
        chosen = available.get(option_id)
        if chosen is None:
            if option_id in KNOWN_OPTION_IDS:
                return ApplyResult.failure(
                    "Этот вариант настройки сейчас недоступен: подходящая видеокарта не найдена."
                )
            return ApplyResult.failure("Неизвестный вариант настройки графики.")

        pids = self.running_pids(browser)
        if pids:
            shown = ", ".join(str(pid) for pid in pids[:5])
            if len(pids) > 5:
                shown += ", …"
            return ApplyResult.failure(
                "Браузер «"
                + _clean_text(browser.name)
                + "» ещё запущен (PID: "
                + shown
                + "). Закройте его и повторите попытку."
            )

        key = self._state_key(browser)
        if chosen.id == LINUX_OPTION_DEFAULT:
            return self._restore_for_default(browser, key)

        override_path = self._override_path(browser.id)
        if self._path_exists(override_path) and not self._is_our_override(override_path):
            return ApplyResult.failure(
                "Для браузера «"
                + _clean_text(browser.name)
                + "» уже есть свой файл ярлыка в папке пользователя, и мы не будем его перезаписывать.",
                details="Файл: "
                + str(override_path)
                + ". Удалите его вручную, если хотите управлять этим браузером через GPU Switch.",
            )

        existing = self._state_entry(key)
        original_exec, original_desktop_path, first_applied_at = self._first_original(existing)
        warnings: List[str] = []

        source_path, base_text, source_entry = self._find_original_desktop(browser)
        if not original_exec:
            original_exec = _strip_text(source_entry.get("Exec", ""))
            if not original_exec:
                original_exec = " ".join(
                    str(part) for part in getattr(browser, "command", ()) or () if str(part)
                )
            if source_path is not None:
                original_desktop_path = str(source_path)
        original_argv = _parse_exec(original_exec)
        if not original_argv:
            original_argv = [
                str(part) for part in getattr(browser, "command", ()) or () if str(part)
            ]
        if not original_argv:
            return ApplyResult.failure(
                "Не удалось определить команду запуска браузера. Настройка не изменена."
            )

        if not base_text.strip():
            base_text = self._read_backup_desktop(key)
        if base_text.strip():
            try:
                backup_path = self.state.backup_file(key, "original.desktop")
                if not backup_path.is_file():
                    self._write_atomic(backup_path, base_text, 0o644)
            except OSError as exc:
                self._record("backup desktop", exc)
                warnings.append("Не удалось сохранить резервную копию ярлыка браузера.")
        else:
            warnings.append("Системный ярлык браузера не найден, используется упрощённый запуск.")
        if source_path is None and original_desktop_path:
            warnings.append("Исходный ярлык браузера не найден — будет создан новый.")
        elif source_path is None:
            warnings.append("Системный ярлык браузера не найден — будет создан новый.")

        mode_part = _safe_filename(chosen.id.split(":", 1)[-1], "mode")
        wrapper_path = self.wrappers_dir / (_safe_filename(browser.id) + "-" + mode_part + ".sh")
        env = self.option_env(chosen)
        script = self._wrapper_script(chosen, env, original_argv)
        try:
            self._write_atomic(wrapper_path, script, 0o755)
        except OSError as exc:
            self._record("wrapper script", exc)
            return ApplyResult.failure(
                "Не удалось создать файл запуска в папке данных приложения.",
                details=str(exc),
            )

        override_text = self._build_override(
            base_text,
            browser,
            chosen,
            wrapper_path,
            original_exec,
            original_desktop_path or (str(source_path) if source_path else ""),
        )
        try:
            self._write_atomic(override_path, override_text, 0o644)
        except OSError as exc:
            self._record("override desktop", exc)
            errors: List[str] = []
            self._remove_path(wrapper_path, errors)
            return ApplyResult.failure(
                "Не удалось сохранить ярлык браузера в папке пользователя.",
                details=str(exc),
            )

        old_wrapper = ""
        if isinstance(existing, Mapping):
            old_wrapper = _strip_text(existing.get("wrapper_path", ""))
        if old_wrapper and not _paths_equal(Path(old_wrapper), wrapper_path):
            self._delete_previous_wrapper(Path(old_wrapper))

        session = self._session_label()
        if chosen.id == LINUX_OPTION_NVIDIA_OFFLOAD and session == "Wayland":
            warnings.append(
                "В сеансе Wayland переключение на NVIDIA может не сработать. Если браузер "
                "запустился не на той видеокарте, выберите сеанс X11 (Xorg) на экране входа."
            )
        if _strip_text(getattr(browser, "source", "")) == "flatpak":
            warnings.append(
                "Браузер установлен через Flatpak: переменные переключения могут не "
                "передаться из песочницы. Проверьте выбранную видеокарту в самом браузере."
            )

        entry: Dict[str, Any] = {
            "platform": LINUX,
            "browser_id": _clean_text(browser.id),
            "browser_name": _clean_text(browser.name),
            "option_id": chosen.id,
            "option_label": chosen.label,
            "applied_at": now_iso(),
            "description": _clean_text(browser.name) + " — " + chosen.label,
            "override_path": str(override_path),
            "wrapper_path": str(wrapper_path),
            "created_by_us": True,
            "original_exec": original_exec,
            "original_desktop_path": original_desktop_path,
            "first_applied_at": first_applied_at or now_iso(),
            "env": dict(env),
            "mode": chosen.id,
            "desktop_id": _clean_text(browser.id),
        }
        try:
            self.state.put(key, entry)
        except Exception as exc:
            self._record("state write " + key, exc)
            cleanup_errors: List[str] = []
            self._remove_path(override_path, cleanup_errors)
            self._remove_path(wrapper_path, cleanup_errors)
            return ApplyResult.failure(
                "Не удалось сохранить запись о настройке. Изменения отменены.",
                details=str(exc),
            )

        details_lines = [
            "Режим: " + chosen.label,
            "Скрипт запуска: " + str(wrapper_path),
            "Ярлык браузера: " + str(override_path),
        ]
        if env:
            details_lines.append(
                "Переменные: " + ", ".join(key + "=" + value for key, value in sorted(env.items()))
            )
        return ApplyResult.success(
            "Готово: браузер «"
            + _clean_text(browser.name)
            + "» будет запускаться с выбранной видеокартой. "
            + "Запустите его заново из меню приложений или кнопкой ниже.",
            details="\n".join(details_lines),
            warnings=warnings,
        )

    def _delete_previous_wrapper(self, path: Path) -> None:
        try:
            if self._path_exists(path) and self._is_our_wrapper(path):
                path.unlink()
        except OSError as exc:
            self._record("delete previous wrapper", exc)

    def apply(self, browser: Browser, option: GpuOption) -> ApplyResult:
        try:
            return self._apply(browser, option)
        except Exception as exc:
            self._record("apply", exc)
            return ApplyResult.failure(
                "Не удалось изменить настройки графики. Попробуйте ещё раз.", details=str(exc)
            )

    # -- restore -----------------------------------------------------------
    def _restore_for_default(self, browser: Browser, key: str) -> ApplyResult:
        entry = self._state_entry(key)
        if entry is None:
            return ApplyResult.success(
                "Для браузера «"
                + _clean_text(browser.name)
                + "» уже используются настройки по умолчанию."
            )
        removed, warnings, error = self._restore_entry(key, entry)
        if error:
            return ApplyResult.failure(
                "Не удалось вернуть настройки по умолчанию для браузера «"
                + _clean_text(browser.name)
                + "».",
                details=error,
            )
        if not removed:
            warnings.append("Изменённых файлов уже не было — запись удалена.")
        return ApplyResult.success(
            "Настройки браузера «"
            + _clean_text(browser.name)
            + "» возвращены к исходным.",
            warnings=warnings,
        )

    def _restore_entry(
        self, key: str, entry: Mapping[str, Any]
    ) -> Tuple[bool, List[str], str]:
        warnings: List[str] = []
        errors: List[str] = []
        if not isinstance(entry, Mapping) or entry.get("platform") != LINUX:
            return (False, warnings, "")
        created_by_us = entry.get("created_by_us") is True
        removed = False
        override_raw = _strip_text(entry.get("override_path", ""))
        wrapper_raw = _strip_text(entry.get("wrapper_path", ""))
        desktop_id = _strip_text(entry.get("desktop_id", "")) or _strip_text(
            entry.get("browser_id", "")
        )

        if created_by_us:
            if override_raw:
                override_path = Path(override_raw)
                if self._path_exists(override_path):
                    if self._is_our_override(override_path):
                        if self._remove_path(override_path, errors):
                            removed = True
                    else:
                        warnings.append(
                            "Файл ярлыка «"
                            + override_raw
                            + "» был изменён другой программой, поэтому оставлен без изменений."
                        )
            candidates: List[Path] = []
            if wrapper_raw:
                candidates.append(Path(wrapper_raw))
            candidates.extend(self._wrapper_candidates(desktop_id))
            seen: Set[str] = set()
            for wrapper in candidates:
                wrapper_key = _path_key(wrapper)
                if wrapper_key in seen:
                    continue
                seen.add(wrapper_key)
                if not self._path_exists(wrapper):
                    continue
                if self._is_our_wrapper(wrapper):
                    if self._remove_path(wrapper, errors):
                        removed = True
                else:
                    warnings.append(
                        "Файл «"
                        + str(wrapper)
                        + "» создан не приложением и оставлен без изменений."
                    )
        else:
            for raw in (override_raw, wrapper_raw):
                if raw and self._path_exists(Path(raw)):
                    warnings.append(
                        "Файл «" + raw + "» создан не приложением и оставлен без изменений."
                    )

        try:
            self.state.remove_backup_dir(key)
        except Exception as exc:
            self._record("remove backup dir " + key, exc)
            warnings.append("Не удалось удалить резервную копию настроек.")

        try:
            self.state.delete(key)
        except Exception as exc:
            self._record("state delete " + key, exc)
            errors.append("Не удалось удалить запись о настройке: " + str(exc))

        self._cleanup_empty_dir(self.wrappers_dir)
        return (removed, warnings, "; ".join(errors))

    def restore_browser(self, browser: Browser) -> ApplyResult:
        try:
            if browser is None or not _strip_text(getattr(browser, "id", "")):
                return ApplyResult.failure(
                    "Не удалось определить браузер. Обновите список браузеров и попробуйте снова."
                )
            key = self._state_key(browser)
            entry = self._state_entry(key)
            if entry is None:
                return ApplyResult.success(
                    "Для браузера «"
                    + _clean_text(browser.name)
                    + "» изменений нет — используются настройки по умолчанию."
                )
            removed, warnings, error = self._restore_entry(key, entry)
            if error:
                return ApplyResult.failure(
                    "Не удалось вернуть настройки браузера «"
                    + _clean_text(browser.name)
                    + "».",
                    details=error,
                    warnings=warnings,
                )
            if not removed:
                warnings.append("Изменённых файлов уже не было — запись удалена.")
            return ApplyResult.success(
                "Настройки браузера «"
                + _clean_text(browser.name)
                + "» возвращены к исходным.",
                warnings=warnings,
            )
        except Exception as exc:
            self._record("restore_browser", exc)
            return ApplyResult.failure(
                "Не удалось вернуть настройки этого браузера. Попробуйте ещё раз.",
                details=str(exc),
            )

    def restore_all(self) -> ApplyResult:
        try:
            try:
                items = self.state.items()
            except Exception as exc:
                self._record("state items", exc)
                return ApplyResult.failure(
                    "Не удалось прочитать сохранённые настройки.", details=str(exc)
                )
            entries = [
                (key, entry)
                for key, entry in items
                if isinstance(entry, dict) and entry.get("platform") == LINUX
            ]
            if not entries:
                return ApplyResult.success("Возвращать нечего: изменений нет.")
            removed_count = 0
            warnings: List[str] = []
            errors: List[str] = []
            for key, entry in entries:
                try:
                    removed, item_warnings, error = self._restore_entry(key, entry)
                except Exception as exc:
                    self._record("restore " + key, exc)
                    removed = False
                    item_warnings = []
                    error = str(exc)
                warnings.extend(item_warnings)
                if error:
                    errors.append(key + ": " + error)
                elif removed:
                    removed_count += 1
            if errors:
                return ApplyResult.failure(
                    "Не удалось вернуть часть настроек.",
                    details="; ".join(errors),
                    warnings=warnings,
                )
            if removed_count:
                message = (
                    "Настройки возвращены к исходным (файлов удалено: "
                    + str(removed_count)
                    + ")."
                )
            else:
                message = "Изменения уже были удалены — возвращать нечего."
            return ApplyResult.success(message, warnings=warnings)
        except Exception as exc:
            self._record("restore_all", exc)
            return ApplyResult.failure(
                "Не удалось вернуть настройки. Попробуйте ещё раз.", details=str(exc)
            )

    def pending_changes(self) -> List[PendingChange]:
        try:
            try:
                items = self.state.items()
            except Exception as exc:
                self._record("state items", exc)
                return []
            changes: List[PendingChange] = []
            for key, entry in items:
                if not isinstance(entry, dict) or entry.get("platform") != LINUX:
                    continue
                try:
                    changes.append(
                        PendingChange(
                            key=key,
                            platform=LINUX,
                            browser_id=_strip_text(entry.get("browser_id", "")),
                            browser_name=_strip_text(
                                entry.get("browser_name", "")
                            )
                            or _strip_text(entry.get("browser_id", "")),
                            option_id=_strip_text(entry.get("option_id", "")),
                            option_label=_strip_text(entry.get("option_label", "")),
                            applied_at=_strip_text(entry.get("applied_at", "")),
                            description=_strip_text(entry.get("description", "")),
                        )
                    )
                except Exception:
                    continue
            changes.sort(key=lambda change: (change.browser_name.lower(), change.key))
            return changes
        except Exception as exc:
            self._record("pending_changes", exc)
            return []

    # -- launch, hints, diagnostics ---------------------------------------
    def launch(self, browser: Browser) -> LaunchResult:
        try:
            command = [
                str(part) for part in getattr(browser, "command", ()) or () if str(part)
            ]
            if not command:
                return LaunchResult(
                    ok=False, message="Не удалось определить команду запуска браузера."
                )
            option = self.current_option(browser)
            env = dict(os.environ)
            env.update(self.option_env(option))
            kwargs: Dict[str, Any] = {
                "start_new_session": True,
                "close_fds": True,
                "cwd": str(self.home),
                "env": env,
                "stdin": subprocess.DEVNULL,
                "stdout": subprocess.DEVNULL,
                "stderr": subprocess.DEVNULL,
            }
            try:
                process = subprocess.Popen(command, **kwargs)
            except (OSError, ValueError, subprocess.SubprocessError) as exc:
                self._record("launch", exc)
                return LaunchResult(
                    ok=False,
                    message="Не удалось запустить браузер «"
                    + _clean_text(getattr(browser, "name", ""))
                    + "». Откройте его из меню приложений.",
                )
            try:
                pid = int(getattr(process, "pid", 0) or 0)
            except (TypeError, ValueError):
                pid = 0
            return LaunchResult(
                ok=True,
                message="Браузер «"
                + _clean_text(getattr(browser, "name", ""))
                + "» запускается.",
                pid=pid,
            )
        except Exception as exc:
            self._record("launch", exc)
            return LaunchResult(
                ok=False,
                message="Не удалось запустить браузер. Откройте его из меню приложений.",
            )

