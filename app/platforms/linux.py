class LinuxBackend:
    """Per-user Linux backend that never requires root and never raises."""

    platform_key = LINUX

    def __init__(
        self,
        home: Optional[Path | str] = None,
        data_dir: Optional[Path | str] = None,
        state: Optional[StateStore] = None,
        sysfs_root: Optional[Path | str] = None,
        proc_root: Optional[Path | str] = None,
        desktop_dirs: Optional[Iterable[Path | str]] = None,
        which: Optional[Callable[[str], Optional[str]]] = None,
        applications_dir: Optional[Path | str] = None,
        os_release_path: Optional[Path | str] = None,
        environ: Optional[Mapping[str, str]] = None,
    ) -> None:
        self._errors: List[str] = []
        self._environ: Dict[str, str] = dict(os.environ if environ is None else environ)

        if home is None:
            try:
                self.home = Path.home()
            except (RuntimeError, OSError):
                self.home = Path("/")
        else:
            self.home = Path(str(home)).expanduser()

        if state is not None:
            self.state = state
        else:
            default_dir = Path(str(data_dir)).expanduser() if data_dir else default_data_dir()
            self.state = StateStore(default_dir)

        if data_dir is not None:
            self.data_dir = Path(str(data_dir)).expanduser()
        else:
            state_dir = getattr(self.state, "data_dir", None)
            self.data_dir = Path(str(state_dir)).expanduser() if state_dir else default_data_dir()

        self.wrappers_dir = self.data_dir / "wrappers"
        self.sysfs_root = Path(str(sysfs_root)) if sysfs_root else Path(DEFAULT_SYSFS_ROOT)
        self.proc_root = Path(str(proc_root)) if proc_root else Path(DEFAULT_PROC_ROOT)
        self._which = which if callable(which) else _default_which
        self.os_release_path = (
            Path(str(os_release_path)).expanduser() if os_release_path else None
        )

        if applications_dir is not None:
            self.applications_dir = Path(str(applications_dir)).expanduser()
        else:
            self.applications_dir = self._default_applications_dir()

        if desktop_dirs is None:
            candidates: List[Path] = [
                Path("/usr/share/applications"),
                Path("/usr/local/share/applications"),
                self.home / ".local" / "share" / "applications",
                self.applications_dir,
                Path("/var/lib/flatpak/exports/share/applications"),
                self.home / ".local" / "share" / "flatpak" / "exports" / "share" / "applications",
            ]
        else:
            candidates = [Path(str(item)).expanduser() for item in desktop_dirs]

        self.desktop_dirs: List[Path] = []
        seen_dirs: Set[str] = set()
        for candidate in candidates:
            key = _path_key(candidate)
            if key in seen_dirs:
                continue
            seen_dirs.add(key)
            self.desktop_dirs.append(candidate)

    # -- construction helpers ---------------------------------------------
    def _default_applications_dir(self) -> Path:
        xdg_data = _strip_text(self._environ.get("XDG_DATA_HOME", ""))
        if xdg_data:
            try:
                return Path(xdg_data).expanduser() / "applications"
            except (RuntimeError, OSError):
                pass
        return self.home / ".local" / "share" / "applications"

    def _record(self, context: str, exc: BaseException) -> None:
        message = context + ": " + type(exc).__name__ + ": " + str(exc)
        self._errors.append(message)
        if len(self._errors) > 60:
            del self._errors[: len(self._errors) - 60]
        log.debug("linux backend: %s", message, exc_info=True)

    def _session_label(self) -> str:
        raw = _strip_text(self._environ.get("XDG_SESSION_TYPE", "")).lower()
        if raw:
            if "wayland" in raw:
                return "Wayland"
            if raw in ("x11", "xorg") or "x11" in raw:
                return "X11"
            return raw.capitalize()
        if _strip_text(self._environ.get("WAYLAND_DISPLAY", "")):
            return "Wayland"
        if _strip_text(self._environ.get("DISPLAY", "")):
            return "X11"
        return ""

    def _current_desktops(self) -> Set[str]:
        values: Set[str] = set()
        for key in ("XDG_CURRENT_DESKTOP", "XDG_SESSION_DESKTOP"):
            raw = _strip_text(self._environ.get(key, ""))
            for part in raw.split(":"):
                part = part.strip().lower()
                if part:
                    values.add(part)
        return values

    def _resolve_executable(self, name: Any) -> Optional[str]:
        text = _strip_text(name)
        if not text:
            return None
        try:
            found = self._which(text)
        except Exception:
            found = None
        if found:
            return str(found)
        try:
            candidate = Path(text).expanduser()
            if candidate.is_file():
                if os.name != "posix" or os.access(str(candidate), os.X_OK):
                    return str(candidate)
        except (OSError, ValueError, RuntimeError):
            return None
        return None

    # -- detection: system -------------------------------------------------
    def os_info(self) -> OsInfo:
        try:
            values: Dict[str, str] = {}
            candidates: Sequence[Path | str]
            if self.os_release_path is not None:
                candidates = (self.os_release_path,)
            else:
                candidates = DEFAULT_OS_RELEASE_PATHS
            for candidate in candidates:
                text = read_text(candidate)
                if text.strip():
                    parsed = _parse_os_release(text)
                    if parsed:
                        values = parsed
                        break
            pretty = _clean_text(values.get("PRETTY_NAME", ""))
            name = pretty or _clean_text(values.get("NAME", "")) or "Linux"
            version = _clean_text(values.get("VERSION_ID", "")) or _clean_text(
                values.get("VERSION", "")
            )
            if not version:
                try:
                    version = _clean_text(_platform.release())
                except Exception:
                    version = ""
            try:
                arch = _strip_text(_platform.machine())
            except Exception:
                arch = ""
            try:
                hostname = _strip_text(socket.gethostname())
            except Exception:
                hostname = ""
            return OsInfo(
                platform_key=LINUX,
                name=name,
                version=version,
                arch=arch,
                hostname=hostname,
                session=self._session_label(),
            )
        except Exception as exc:
            self._record("os_info", exc)
            return OsInfo(platform_key=LINUX, name="Linux", version="", arch="", hostname="")

    def _vendor_of(self, vendor_id: str) -> str:
        raw = _strip_text(vendor_id).lower()
        if raw in VENDOR_NAMES:
            return VENDOR_NAMES[raw]
        if raw.startswith("0x") and len(raw) == 6:
            return VENDOR_NAMES.get(raw, "other")
        return "other"

    def _classify(self, vendor: str, boot_vga: bool, driver: str) -> str:
        if vendor == "virtual" or driver in VIRTUAL_DRIVERS:
            return "virtual"
        if vendor == "nvidia":
            return "discrete"
        if vendor == "intel":
            return "integrated"
        if vendor == "amd":
            return "integrated" if boot_vga else "discrete"
        if driver in ("i915", "xe"):
            return "integrated"
        if driver in ("amdgpu", "radeon", "nouveau"):
            return "discrete"
        return "unknown"

    def _pci_address(self, device: Path) -> str:
        uevent = read_text(device / "uevent")
        for raw in uevent.splitlines():
            line = raw.strip()
            if line.startswith("PCI_SLOT_NAME="):
                value = _strip_text(line.split("=", 1)[1]).lower()
                if PCI_ADDRESS_RE.match(value):
                    return value
        target = _read_link(device)
        base = _basename(target).lower()
        if PCI_ADDRESS_RE.match(base):
            return base
        if PCI_ADDRESS_RE.match(device.name.lower()):
            return device.name.lower()
        return ""

    def _nvidia_model(self, pci_address: str) -> str:
        if not pci_address:
            return ""
        # The real /proc/driver/nvidia/gpus/<slot>/information directory uses
        # the PCI slot name with ':' in it.  A ':' is not a legal file name
        # character on every OS (test fixtures therefore use '_'), so both
        # spellings are tried and the first readable one wins.
        candidates = [pci_address]
        safe_address = pci_address.replace(":", "_")
        if safe_address not in candidates:
            candidates.append(safe_address)
        for candidate in candidates:
            info = read_text(
                self.proc_root / "driver" / "nvidia" / "gpus" / candidate / "information"
            )
            for raw in info.splitlines():
                line = raw.strip()
                if line.lower().startswith("model:"):
                    value = _clean_text(line.split(":", 1)[1])
                    if value:
                        return value
        return ""

    def _gpu_display_name(
        self,
        device: Path,
        vendor: str,
        device_id: str,
        pci_address: str,
        driver: str,
        card_name: str,
    ) -> str:
        model = self._nvidia_model(pci_address)
        if model:
            return model
        for key in ("product_name", "product", "label"):
            value = _clean_text(read_text(device / key))
            if value:
                return value
        suffix = ""
        if device_id:
            suffix = " (" + device_id + ")"
        elif pci_address:
            suffix = " (PCI " + pci_address.split(":")[-1] + ")"
        labels = {
            "nvidia": "Видеокарта NVIDIA",
            "intel": "Графика Intel",
            "amd": "Видеокарта AMD",
            "virtual": "Виртуальная видеокарта",
            "other": "Видеокарта",
        }
        label = labels.get(vendor, "Видеокарта")
        if not suffix and card_name:
            suffix = " (" + card_name + ")"
        return label + suffix

    def _gpu_from_dir(self, device: Path, card_name: str = "") -> Optional[Gpu]:
        vendor_id = _strip_text(read_text(device / "vendor")).lower()
        device_id = _strip_text(read_text(device / "device")).lower()
        device_class = _strip_text(read_text(device / "class")).lower()
        if not vendor_id and not device_id:
            return None
        pci_address = self._pci_address(device)
        driver = _basename(_read_link(device / "driver"))
        boot_vga = _strip_text(read_text(device / "boot_vga")) == "1"
        memory_mb = _parse_vram_mb(device / "mem_info_vram_total")
        if not memory_mb:
            memory_mb = _parse_vram_mb(device / "mem_info_vis_vram_total")
        vendor = self._vendor_of(vendor_id)
        if driver in VIRTUAL_DRIVERS:
            vendor = "virtual"
        kind = self._classify(vendor, boot_vga, driver)
        name = self._gpu_display_name(device, vendor, device_id, pci_address, driver, card_name)
        detail_parts: List[str] = []
        if vendor_id:
            detail_parts.append("vendor " + vendor_id)
        if device_id:
            detail_parts.append("device " + device_id)
        if driver:
            detail_parts.append("driver " + driver)
        if boot_vga:
            detail_parts.append("boot vga")
        if device_class:
            detail_parts.append("class " + device_class)
        gpu_id = "linux:gpu:" + (pci_address or card_name or vendor_id or "unknown")
        return Gpu(
            id=gpu_id,
            name=name,
            vendor=vendor,
            kind=kind,
            driver=driver,
            memory_mb=memory_mb,
            pci_address=pci_address,
            detail=" · ".join(detail_parts),
        )

    def _scan_drm(self, found: Dict[str, Gpu], order: List[str]) -> None:
        drm_root = self.sysfs_root / "class" / "drm"
        try:
            entries = sorted(drm_root.iterdir(), key=lambda item: item.name)
        except (OSError, ValueError):
            return
        for card in entries:
            if not re.fullmatch(r"card\d+", card.name):
                continue
            device = card / "device"
            try:
                if not device.is_dir():
                    continue
            except OSError:
                continue
            try:
                gpu = self._gpu_from_dir(device, card.name)
            except Exception as exc:
                self._record("gpu card " + card.name, exc)
                continue
            if gpu is None:
                continue
            key = gpu.pci_address or "drm:" + card.name
            if key not in found:
                found[key] = gpu
                order.append(key)

    def _scan_pci(self, found: Dict[str, Gpu], order: List[str]) -> None:
        pci_root = self.sysfs_root / "bus" / "pci" / "devices"
        try:
            entries = sorted(pci_root.iterdir(), key=lambda item: item.name)
        except (OSError, ValueError):
            return
        for device in entries:
            try:
                if not device.is_dir():
                    continue
            except OSError:
                continue
            try:
                if not _is_display_class(read_text(device / "class")):
                    continue
                gpu = self._gpu_from_dir(device, "")
            except Exception as exc:
                self._record("pci device " + device.name, exc)
                continue
            if gpu is None:
                continue
            key = gpu.pci_address or "pci:" + device.name
            existing = found.get(key)
            if existing is None:
                found[key] = gpu
                order.append(key)
            else:
                found[key] = _merge_gpu(existing, gpu)

    def list_gpus(self) -> List[Gpu]:
        try:
            found: Dict[str, Gpu] = {}
            order: List[str] = []
            self._scan_drm(found, order)
            self._scan_pci(found, order)
            gpus = [found[key] for key in order if key in found]
            gpus.sort(key=lambda item: (KIND_ORDER.get(item.kind, 9), item.name.lower(), item.id))
            return gpus
        except Exception as exc:
            self._record("list_gpus", exc)
            return []

    # -- detection: browsers ----------------------------------------------
    def _visible_in_session(self, entry: Mapping[str, str]) -> bool:
        current = self._current_desktops()
        only_show = {
            part.strip().lower()
            for part in str(entry.get("OnlyShowIn", "")).split(";")
            if part.strip()
        }
        not_show = {
            part.strip().lower()
            for part in str(entry.get("NotShowIn", "")).split(";")
            if part.strip()
        }
        if only_show and current and not (only_show & current):
            return False
        if not_show and current and (not_show & current):
            return False
        return True

    def _parse_flatpak(
        self, argv: Sequence[str], command_index: int
    ) -> Optional[Tuple[str, str, str]]:
        if not argv or command_index >= len(argv):
            return None
        token = argv[command_index]
        if _basename(token).lower() not in ("flatpak", "flatpak-spawn"):
            return None
        if command_index + 2 >= len(argv):
            return None
        if argv[command_index + 1].strip() != "run":
            return None
        app_id = ""
        inner = ""
        for index in range(command_index + 2, len(argv)):
            item = argv[index]
            if item.startswith("--command="):
                inner = _strip_text(item.split("=", 1)[1])
            elif item.startswith("-"):
                continue
            elif not app_id and FLATPAK_APP_ID_RE.match(item):
                app_id = item
        if not app_id:
            return None
        if not inner:
            inner = app_id.rsplit(".", 1)[-1]
        return (token, app_id, inner)

    def _browser_from_desktop(self, path: Path) -> Optional[Browser]:
        entry = _parse_desktop_entry(path)
        if not entry:
            return None
        # Our own override is not a browser definition: the system .desktop file
        # with the same id is used for display, current_option() reads the marker.
        if _strip_text(entry.get(MARKER_MODE, "")):
            return None
        if _is_true(entry.get("Hidden")) or _is_true(entry.get("NoDisplay")):
            return None
        entry_type = _strip_text(entry.get("Type", ""))
        if entry_type and entry_type != "Application":
            return None
        if not self._visible_in_session(entry):
            return None
        exec_value = _strip_text(entry.get("Exec", ""))
        if not exec_value:
            return None
        argv = _parse_exec(exec_value)
        if not argv:
            return None
        try_exec = _strip_text(entry.get("TryExec", ""))
        if try_exec and not self._resolve_executable(try_exec):
            return None

        categories = {
            part.strip().lower()
            for part in str(entry.get("Categories", "")).split(";")
            if part.strip()
        }
        web_category = "webbrowser" in categories
        command_index = _command_index(argv)
        command_token = argv[command_index]
        flatpak_info = self._parse_flatpak(argv, command_index)
        package = ""
        processes: Set[str] = set()

        if flatpak_info is not None:
            exe_token, app_id, inner = flatpak_info
            resolved = self._resolve_executable(exe_token)
            if not resolved:
                return None
            package = app_id
            engine_match = _match_known_browser(inner) or _match_known_browser(
                _basename(app_id)
            )
            if engine_match is None and not web_category:
                return None
            if engine_match is not None:
                processes.update(engine_match[2])
            processes.update(
                {app_id.lower(), app_id.rsplit(".", 1)[-1].lower(), inner.lower()}
            )
            engine = engine_match[0] if engine_match else "other"
        else:
            resolved = self._resolve_executable(command_token)
            if not resolved:
                return None
            engine_match = _match_known_browser(_basename(command_token))
            if engine_match is None and not web_category:
                return None
            if engine_match is not None:
                processes.update(engine_match[2])
            processes.add(_basename(command_token).lower())
            processes.add(_basename(resolved).lower())
            engine = engine_match[0] if engine_match else "other"

        processes = {
            name
            for name in (str(item).strip().lower() for item in processes)
            if name and name not in GENERIC_PROCESS_NAMES
        }
        display_name = _clean_text(_desktop_unescape(entry.get("Name", "")))
        if not display_name:
            display_name = engine_match[1] if engine_match is not None else ""
        if not display_name:
            display_name = _basename(command_token) or "Браузер"
        return Browser(
            id=path.name[: -len(".desktop")] if path.name.endswith(".desktop") else path.name,
            name=display_name,
            executable=resolved,
            launch_command=tuple(argv),
            engine=engine,
            version="",
            package=package,
            desktop_file=str(path),
            process_names=tuple(sorted(processes)),
            source="flatpak" if package else "desktop",
            supported=True,
        )

    def _desktop_rank(self, directory: Path, index: int) -> Tuple[int, int]:
        return (0 if _is_under(directory, self.home) else 1, index)

    def list_browsers(self) -> List[Browser]:
        try:
            best: Dict[str, Tuple[Tuple[int, int], Browser]] = {}
            for index, directory in enumerate(self.desktop_dirs):
                try:
                    entries = sorted(directory.iterdir(), key=lambda item: item.name)
                except (OSError, ValueError):
                    continue
                for path in entries:
                    if not path.name.endswith(".desktop"):
                        continue
                    try:
                        browser = self._browser_from_desktop(path)
                    except Exception as exc:
                        self._record("desktop file " + str(path), exc)
                        continue
                    if browser is None:
                        continue
                    rank = self._desktop_rank(directory, index)
                    previous = best.get(browser.id)
                    if previous is None or rank < previous[0]:
                        best[browser.id] = (rank, browser)
            browsers = [browser for _, browser in best.values()]
            browsers.sort(key=lambda item: (item.name.lower(), item.id))
            return browsers
        except Exception as exc:
            self._record("list_browsers", exc)
            return []

